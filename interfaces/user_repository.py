from typing import Protocol, List, Optional
from domain.entities.user import User
from interfaces.base_repository import Repository

class UserRepository(Repository[User], Protocol):
    def find_by_username(self, username: str) -> Optional[User]: ...
    def find_by_branch_id(self, branch_id: str) -> List[User]: ...
    def find_by_branch_ids(self, branch_ids: List[str]) -> List[User]: ...
    def update_password(self, username: str, password_hash: str) -> bool: ...
    def update_extra_fields(self, user_id: str, extra_fields: dict) -> bool: ...
